// Devnagari numeral mapping
export const toDevnagariNum = (num) => {
    const devnagariDigits = ['०', '१', '२', '३', '४', '५', '६', '७', '८', '९'];
    return String(num).split('').map(char => {
        const digit = parseInt(char);
        return isNaN(digit) ? char : devnagariDigits[digit];
    }).join('');
};
